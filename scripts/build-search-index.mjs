#!/usr/bin/env node
// Generates src/data/search-index.json — the client-side site search index
// (issue #408). No search dependency, no server: every route's title +
// description (extracted from its metadata export), plus guide promises and
// blog posts, in one small committed JSON the /search/ page filters in the
// browser.
//
//   node scripts/build-search-index.mjs           # (re)generate
//   node scripts/build-search-index.mjs --check   # exit 1 if stale (CI)

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const appDir = join(root, 'src', 'app')
const OUT_PATH = join(root, 'src', 'data', 'search-index.json')

const str = `('(?:[^'\\\\]|\\\\.)*'|"(?:[^"\\\\]|\\\\.)*")`
const titleRe = new RegExp(`title:\\s*${str}`)
const descRe = new RegExp(`description:\\s*\\n?\\s*${str}`)
const unquote = (s) => s.slice(1, -1).replace(/\\(['"])/g, '$1')

const entries = []

// 1. Routes: title + description from each page.tsx metadata export.
for (const dir of readdirSync(appDir, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue
  const pagePath = join(appDir, dir.name, 'page.tsx')
  if (!existsSync(pagePath)) continue
  const src = readFileSync(pagePath, 'utf8')
  if (src.includes('noindex: true') || src.includes('robots: { index: false')) continue
  const t = titleRe.exec(src)
  const d = descRe.exec(src)
  if (!t || !d) continue
  entries.push({
    title: unquote(t[1]),
    description: unquote(d[1]),
    href: `/${dir.name}/`,
    type: 'page',
  })
}

// 2. Guides: promises make better search text than page descriptions.
const guides = JSON.parse(readFileSync(join(root, 'src/data/guides.json'), 'utf8'))
for (const g of guides.guides) {
  entries.push({ title: g.title, description: g.promise, href: g.href, type: 'guide' })
}

// 3. Blog posts.
const blog = JSON.parse(readFileSync(join(root, 'src/data/blog-posts.json'), 'utf8'))
for (const p of blog.posts) {
  entries.push({
    title: p.heading,
    description: p.description,
    href: p.href ?? '/blog/',
    type: 'post',
  })
}

// Dedupe by href, first entry wins (guides/posts add hrefs pages already
// have — keep the richer page entry, then append distinct guide/post hrefs).
const seen = new Set()
const deduped = entries.filter((e) => (seen.has(e.href) ? false : (seen.add(e.href), true)))
deduped.sort((a, b) => a.href.localeCompare(b.href))

const output =
  JSON.stringify(
    {
      _comment:
        'GENERATED by scripts/build-search-index.mjs — do not edit. Regenerate: node scripts/build-search-index.mjs',
      entries: deduped,
    },
    null,
    2
  ) + '\n'

if (process.argv.includes('--check')) {
  let committed = ''
  try {
    committed = readFileSync(OUT_PATH, 'utf8')
  } catch {
    /* missing counts as stale */
  }
  if (committed !== output) {
    console.error('search-index.json is stale — regenerate: node scripts/build-search-index.mjs')
    process.exit(1)
  }
  console.log('search-index.json is up to date.')
} else {
  writeFileSync(OUT_PATH, output)
  console.log(`Wrote ${OUT_PATH} (${deduped.length} entries)`)
}
